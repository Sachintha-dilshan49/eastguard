#!/usr/bin/env bash
# Provisions EastGuard control-plane API credentials: one high-entropy secret per principal.
# Run from anywhere: ./scripts/gen-credentials.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="$ROOT/keys"
FORCE=false
TELEMETRY_KEYS=false
ROTATE=""
RETIRE=""
REVOKE=""
ADD=""

PRINCIPALS=(
    "admin:ADMIN"
    "operator:OPERATOR"
    "viewer:VIEWER"
    "gw-app-02:GATEWAY"
    "gw-app-03:GATEWAY"
    "tokensvc:ISSUER"
    "token-server:ISSUER"
    "detector:DETECTOR"
    "console-viewer:VIEWER"
    "console-operator:OPERATOR"
    "console-admin:ADMIN"
)

TELEMETRY_PRODUCERS=(
    "gw-app-02"
    "gw-app-03"
    "tokensvc"
    "token-server"
)

while [[ $# -gt 0 ]]; do
    case "$1" in
        -OutDir|--out-dir)
            OUT_DIR="$2"
            shift 2
            ;;
        -Force|--force)
            FORCE=true
            shift
            ;;
        -Rotate|--rotate)
            ROTATE="$2"
            shift 2
            ;;
        -Retire|--retire)
            RETIRE="$2"
            shift 2
            ;;
        -Revoke|--revoke)
            REVOKE="$2"
            shift 2
            ;;
        -Add|--add)
            ADD="$2"
            shift 2
            ;;
        -TelemetryKeys|--telemetry-keys)
            TELEMETRY_KEYS=true
            shift
            ;;
        *)
            echo "Unknown option: $1" >&2
            exit 2
            ;;
    esac
done

mkdir -p "$OUT_DIR"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"
API_DIR="$OUT_DIR/api"
TELEMETRY_DIR="$OUT_DIR/telemetry"
CRED_FILE="$OUT_DIR/control-credentials.properties"

mkdir -p "$API_DIR" "$TELEMETRY_DIR"

new_secret() {
    local name="$1"
    local secret_file="$API_DIR/$name.secret"
    local raw_file="$API_DIR/.tmp.$name.raw"
    head -c 32 /dev/urandom > "$raw_file"
    local b64
    b64=$(base64 < "$raw_file" | tr '+/' '-_' | tr -d '=\r\n')
    printf "%s" "$b64" > "$secret_file"
    chmod 600 "$secret_file" 2>/dev/null || true
    local digest
    digest=$(sha256sum "$raw_file" | awk '{print $1}')
    rm -f "$raw_file"
    echo "$digest"
}

new_telemetry_key() {
    local name="$1"
    local key_file="$TELEMETRY_DIR/$name.key"
    if [[ -f "$key_file" && "$FORCE" != true ]]; then
        echo "  telemetry/$name.key exists (kept; -Force replaces it)"
        return
    fi
    local raw_file="$TELEMETRY_DIR/.tmp.$name.raw"
    head -c 32 /dev/urandom > "$raw_file"
    local b64
    b64=$(base64 < "$raw_file" | tr '+/' '-_' | tr -d '=\r\n')
    printf "%s" "$b64" > "$key_file"
    chmod 600 "$key_file" 2>/dev/null || true
    rm -f "$raw_file"
    echo "  telemetry/$name.key"
}

if [[ "$TELEMETRY_KEYS" == true ]]; then
    for p in "${TELEMETRY_PRODUCERS[@]}"; do
        new_telemetry_key "$p"
    done
    exit 0
fi

if [[ -f "$CRED_FILE" && "$FORCE" != true && -z "$ROTATE" && -z "$RETIRE" && -z "$REVOKE" && -z "$ADD" ]]; then
    echo "$CRED_FILE already exists. Use -Force to replace everything, or -Rotate/-Retire/-Revoke <principal>." >&2
    exit 1
fi

declare -A PRINCIPAL_ROLES
declare -A PRINCIPAL_DIGESTS
declare -A PRINCIPAL_ENABLED
ORDERED_NAMES=()

load_credentials() {
    if [[ ! -f "$CRED_FILE" ]]; then
        return
    fi
    local principals_line
    principals_line=$(grep '^principals=' "$CRED_FILE" | cut -d'=' -f2-)
    IFS=',' read -ra names <<< "$principals_line"
    for name in "${names[@]}"; do
        name=$(echo "$name" | tr -d ' \r\n')
        [[ -z "$name" ]] && continue
        ORDERED_NAMES+=("$name")
        PRINCIPAL_ROLES["$name"]=$(grep "^principal\.$name\.role=" "$CRED_FILE" | cut -d'=' -f2- | tr -d ' \r\n')
        PRINCIPAL_DIGESTS["$name"]=$(grep "^principal\.$name\.sha256=" "$CRED_FILE" | cut -d'=' -f2- | tr -d ' \r\n')
        local en
        en=$(grep "^principal\.$name\.enabled=" "$CRED_FILE" | cut -d'=' -f2- | tr -d ' \r\n')
        if [[ "$en" == "false" ]]; then
            PRINCIPAL_ENABLED["$name"]="false"
        else
            PRINCIPAL_ENABLED["$name"]="true"
        fi
    done
}

write_credentials() {
    local tmp="$CRED_FILE.tmp"
    {
        echo "# EastGuard control-plane API credentials: SHA-256 digests only, never secrets."
        echo "# Generated by scripts/gen-credentials.sh. Reloaded by the control plane when it changes."
        local plist=""
        for name in "${ORDERED_NAMES[@]}"; do
            plist="${plist:+$plist,}$name"
        done
        echo "principals=$plist"
        for name in "${ORDERED_NAMES[@]}"; do
            echo "principal.$name.role=${PRINCIPAL_ROLES[$name]}"
            echo "principal.$name.sha256=${PRINCIPAL_DIGESTS[$name]}"
            echo "principal.$name.enabled=${PRINCIPAL_ENABLED[$name]}"
        done
    } > "$tmp"
    mv "$tmp" "$CRED_FILE"
    chmod 600 "$CRED_FILE" 2>/dev/null || true
}

if [[ -n "$ROTATE" ]]; then
    load_credentials
    if [[ -z "${PRINCIPAL_ROLES[$ROTATE]:-}" ]]; then
        echo "unknown principal '$ROTATE' in $CRED_FILE" >&2
        exit 1
    fi
    new_d=$(new_secret "$ROTATE")
    PRINCIPAL_DIGESTS["$ROTATE"]="$new_d,${PRINCIPAL_DIGESTS[$ROTATE]}"
    PRINCIPAL_ENABLED["$ROTATE"]="true"
    write_credentials
    echo "rotated $ROTATE: new secret in api/$ROTATE.secret; the old digest stays valid until -Retire $ROTATE"
    exit 0
fi

if [[ -n "$RETIRE" ]]; then
    load_credentials
    if [[ -z "${PRINCIPAL_ROLES[$RETIRE]:-}" ]]; then
        echo "unknown principal '$RETIRE' in $CRED_FILE" >&2
        exit 1
    fi
    first_d=$(echo "${PRINCIPAL_DIGESTS[$RETIRE]}" | cut -d',' -f1)
    PRINCIPAL_DIGESTS["$RETIRE"]="$first_d"
    write_credentials
    echo "retired old digest(s) of $RETIRE"
    exit 0
fi

if [[ -n "$REVOKE" ]]; then
    load_credentials
    if [[ -z "${PRINCIPAL_ROLES[$REVOKE]:-}" ]]; then
        echo "unknown principal '$REVOKE' in $CRED_FILE" >&2
        exit 1
    fi
    PRINCIPAL_ENABLED["$REVOKE"]="false"
    write_credentials
    rm -f "$API_DIR/$REVOKE.secret"
    echo "revoked $REVOKE"
    exit 0
fi

if [[ -n "$ADD" ]]; then
    load_credentials
    IFS=',' read -ra add_entries <<< "$ADD"
    for entry in "${add_entries[@]}"; do
        entry=$(echo "$entry" | tr -d ' \r\n')
        [[ -z "$entry" ]] && continue
        name=$(echo "$entry" | cut -d':' -f1)
        role=$(echo "$entry" | cut -d':' -f2)
        ORDERED_NAMES+=("$name")
        PRINCIPAL_ROLES["$name"]="$role"
        PRINCIPAL_DIGESTS["$name"]="$(new_secret "$name")"
        PRINCIPAL_ENABLED["$name"]="true"
        echo "  api/$name.secret  ($role)"
    done
    write_credentials
    echo "added principals to $CRED_FILE"
    exit 0
fi

# Fresh generation
for entry in "${PRINCIPALS[@]}"; do
    name=$(echo "$entry" | cut -d':' -f1)
    role=$(echo "$entry" | cut -d':' -f2)
    ORDERED_NAMES+=("$name")
    PRINCIPAL_ROLES["$name"]="$role"
    PRINCIPAL_DIGESTS["$name"]="$(new_secret "$name")"
    PRINCIPAL_ENABLED["$name"]="true"
    echo "  api/$name.secret  ($role)"
done
write_credentials
for p in "${TELEMETRY_PRODUCERS[@]}"; do
    new_telemetry_key "$p"
done
echo "wrote $CRED_FILE"

